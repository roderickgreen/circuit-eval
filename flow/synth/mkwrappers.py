#!/usr/bin/env python3
"""Generate io_wrappers.v: scalar-port wrappers whose port names and order
match the reference BLIF interfaces exactly, so ABC-written BLIFs of
these tops drop straight into verify_value.py / the bench tooling with
no rename step.

usage: mkwrappers.py <out.v>
"""
import sys


def wrapper(name, core, in_ports, in_conn, out_ports, out_port):
    """in_conn: (bus_expr, port_name) core connection; out: bus -> scalars.
    out_port is the core's output port name; the scalar pin names in
    out_ports are frozen independently of it."""
    lines = [f"module {name} ("]
    lines.append("  input " + ", ".join(in_ports) + ",")
    lines.append("  output " + ", ".join(out_ports))
    lines.append(");")
    lines.append(f"  wire [{len(out_ports) - 1}:0] {out_port};")
    lines.append(f"  {core} u ({in_conn}, .{out_port}({out_port}));")
    lines.append("  assign {" + ", ".join(reversed(out_ports)) + "} = "
                 + out_port + ";")
    lines.append("endmodule\n")
    return "\n".join(lines)


mods = []

# rank_value_io: inputs c{r}_{b}, r 12..0, b 0..2 (rankvalue.py order);
# core bus counts[3*r+2 : 3*r] = {c{r}_2, c{r}_1, c{r}_0}
rin = [f"c{r}_{b}" for r in range(12, -1, -1) for b in range(3)]
rcat = ", ".join(f"c{r}_{b}" for r in range(12, -1, -1)
                 for b in range(2, -1, -1))
mods.append(wrapper("rank_value_io", "rank_value", rin,
                    ".counts({" + rcat + "})",
                    [f"rk{b}" for b in range(24)], "value"))

# flush_value_io: inputs m{r}, r 12..0 (flushvalue.py order)
fin = [f"m{r}" for r in range(12, -1, -1)]
fcat = ", ".join(f"m{r}" for r in range(12, -1, -1))
mods.append(wrapper("flush_value_io", "flush_value", fin,
                    ".mask({" + fcat + "})",
                    [f"fl{b}" for b in range(24)], "value"))

# holdem_value_io: inputs x{r}_{s}, r 12..0, s 0..3 (factored2.py order);
# core bus cards[4*r + s]
xin = [f"x{r}_{s}" for r in range(12, -1, -1) for s in range(4)]
xcat = ", ".join(f"x{r}_{s}" for r in range(12, -1, -1)
                 for s in range(3, -1, -1))
mods.append(wrapper("holdem_value_io", "holdem_value", xin,
                    ".cards({" + xcat + "})",
                    [f"e{b}" for b in range(24)], "value"))

# omaha_value_io: inputs h0..h51 b0..b51 (omahavalue.py order); core buses
# hole[4*r+s] / board[4*r+s] = card id order, so bus bit i = pin {h,b}{i}
oin = [f"h{i}" for i in range(52)] + [f"b{i}" for i in range(52)]
hcat = ", ".join(f"h{i}" for i in range(51, -1, -1))
bcat = ", ".join(f"b{i}" for i in range(51, -1, -1))
mods.append(wrapper("omaha_value_io", "omaha_value", oin,
                    ".hole({" + hcat + "}), .board({" + bcat + "})",
                    [f"ov{b}" for b in range(24)], "value"))

# low_core_io: inputs hp0..hp7 bp0..bp7, outputs lo0..lo7 (compose_low.py
# positional order); core buses hole[i]/board[i], bit 0 = ace .. 7 = eight
lin = [f"hp{i}" for i in range(8)] + [f"bp{i}" for i in range(8)]
hpcat = ", ".join(f"hp{i}" for i in range(7, -1, -1))
bpcat = ", ".join(f"bp{i}" for i in range(7, -1, -1))
mods.append(wrapper("low_core_io", "low_core", lin,
                    ".hole({" + hpcat + "}), .board({" + bpcat + "})",
                    [f"lo{b}" for b in range(8)], "low"))

# cmp{8,24}_io: inputs a0..aN b0..bN (bit 0 = LSB), outputs gt, eq.
# The comparator outputs are already scalar, so only the input buses
# need unpacking.
for w in (8, 24):
    cin = ([f"a{i}" for i in range(w)] + [f"b{i}" for i in range(w)])
    acat = ", ".join(f"a{i}" for i in range(w - 1, -1, -1))
    bcat = ", ".join(f"b{i}" for i in range(w - 1, -1, -1))
    mods.append("\n".join([
        f"module cmp{w}_io (",
        "  input " + ", ".join(cin) + ",",
        "  output gt, eq",
        ");",
        f"  cmp{w} u (.a({{{acat}}}), .b({{{bcat}}}), .gt(gt), .eq(eq));",
        "endmodule\n",
    ]))

with open(sys.argv[1], "w") as f:
    f.write("// GENERATED by mkwrappers.py -- scalar-port wrappers matching\n"
            "// the reference BLIF pin names/order. Do not edit by hand.\n\n")
    f.write("\n".join(mods))
print(f"wrote {len(mods)} wrappers")
