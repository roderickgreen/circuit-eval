#!/usr/bin/env python3
"""Board-major exact-enumeration equity kernel generator for WebGPU.

One invocation = one board (one entry of the host-built board list);
villain combos ride the 32 bitslice lanes in an inner loop of lane-groups
(32 consecutive villain-list entries each).  The design:

  - board planes are scalar words, not a per-lane array -- the dynamically
    indexed structure that was vendor-divergent (device-memory scratch on
    RDNA3, occupancy collapse on Apple) does not exist here
  - hero is evaluated once per board (not once per 32 deals) and carried
    as compressed scalars into an inlined compare against each villain
    group
  - villain lane masks are read straight from the villain list and turned
    into plane words by two unrolled 32x32 bit transposes (Hacker's
    Delight 7-3); every private-array index is a constant after unroll,
    so everything stays in registers.

The kernel contains no combinatorics: both lists are enumerated on the CPU
(demo/src/lib/worklist.ts) as packed card-mask pairs in plane space, the same
"masks in, transpose at the boundary" shape as the C library's mask API
(bspack.c).  The lists are independent, so a villain sharing a card with
the board is possible; such pairs are not deals and are dropped in-kernel
by one mask test per lane -- exactly C(nlive - k, v) villains survive each
board, so the deals tally matches the host's combinatorial cross-check.

A partly unknown hero is a third axis, and it lives on the uniform: the
host enumerates hero draws itself, rewriting the hero mask (known |
drawn) and the hdraw words (the drawn part alone) between dispatches.
List entries claiming a drawn hero card are dropped the same way -- a
board by an invocation-level test before the hero eval, a villain by the
per-lane mask test.

The host chunks the villain axis in lane-group units (Params.gbase/ngrps),
so a dispatch stays wide (all boards, full occupancy) but shallow (bounded
inner loop) -- that bounds progress cadence and cancel latency on spots
whose villain axis is huge.

Styles (v=0 spots stay on the deal-major kernel either way: lanes must
carry boards when there is nothing to draw for the villain):

  holdem  52-input circuit, hole and board share the presence planes.
  omaha   104-input circuits (hole planes 0..51 by card id, board planes
          52..103); board planes are uniform across lanes, so they are
          broadcast from two scalars set once per invocation.  --low adds
          the 8-or-better low circuit and switches the tally to
          quarter-pot units, matching equity_wgsl.py.

usage: equity_bm_wgsl.py --style holdem|omaha --high <high.blif>
                         [--low <low.blif>] <out.wgsl>
       equity_bm_wgsl.py --selftest        (verify the transpose network)
"""
import sys

from equity_wgsl import (emit_circuit_fn, plane_of_card, transpose_stmts,
                         lane_load_stmts, selftest)


def emit_header(meta, pc):
    return f"""// generated by equity_bm_wgsl.py -- do not edit
// meta: equity-bm {meta}
// planeOfCard: {",".join(map(str, pc))}
alias word = u32;
const ZERO = 0u;
const ONES = 0xffffffffu;

struct Params {{
  hero_lo: u32,    // hero hole mask, plane space
  hero_hi: u32,
  vill_lo: u32,    // known villain holes; the drawn part is per list entry
  vill_hi: u32,
  board_lo: u32,   // revealed board mask, plane space
  board_hi: u32,
  nboards: u32,    // board list length: one invocation per board
  nvillains: u32,  // villain list length
  base: u32,       // first invocation index of this dispatch (chunking)
  ngrps: u32,      // villain lane-groups (32 list entries each) THIS
                   // dispatch: the host chunks the villain axis in group
                   // units so a dispatch stays wide (all boards) but
                   // shallow (bounded inner loop)
  gbase: u32,      // first lane-group of this dispatch
  hdraw_lo: u32,   // drawn (unknown) hero cards this dispatch -- the host
  hdraw_hi: u32,   //   enumerates hero draws by rewriting the uniform; a
                   //   subset of the hero mask, used only to drop list
                   //   entries that claim one of these cards
}}
@group(0) @binding(0) var<uniform> P: Params;
// work lists, built host-side (demo/src/lib/worklist.ts): one entry per
// combination of drawn cards, as a plane-space mask pair (.x holds planes
// 0..31, .y planes 32..51)
@group(0) @binding(1) var<storage, read> boards: array<vec2<u32>>;
@group(0) @binding(2) var<storage, read> villains: array<vec2<u32>>;
// counter i is the u64 pair (tally[2i], tally[2i+1]) -- preflop-vs-random
// omaha spots run to ~10^11 deals, past any single u32
@group(0) @binding(3) var<storage, read_write> tally: array<atomic<u32>>;

fn tadd(i: u32, x: u32) {{
  let old = atomicAdd(&tally[2u * i], x);
  if (old > ONES - x) {{ atomicAdd(&tally[2u * i + 1u], 1u); }}
}}

fn maskbit(lo: u32, hi: u32, p: u32) -> word {{
  var w = lo;
  if (p >= 32u) {{ w = hi; }}
  if (((w >> (p & 31u)) & 1u) == 1u) {{ return ONES; }}
  return ZERO;
}}"""


PROLOGUE = """@compute @workgroup_size(64)
fn main_equity_bm(@builtin(global_invocation_id) g: vec3<u32>) {
  let gidx = P.base + g.x;
  if (gidx >= P.nboards) { return; }
  // this invocation's drawn board: one plane-space mask pair from the list
  let bd = boards[gidx];
  // a board claiming a drawn hero card is not part of any deal
  if (((bd.x & P.hdraw_lo) | (bd.y & P.hdraw_hi)) != 0u) { return; }
"""


def group_head_stmts():
    """Open the villain lane-group loop: group bounds, the partial-group
    valid mask, and the 32 lane loads (villains colliding with this board
    or the drawn hero cards leave `valid`)."""
    lines = ["""  let cl_lo = bd.x | P.hdraw_lo;
  let cl_hi = bd.y | P.hdraw_hi;
  for (var grp = 0u; grp < P.ngrps; grp++) {
    let v0 = (P.gbase + grp) * 32u;
    let rem = P.nvillains - v0;
    var valid = ONES;
    if (rem < 32u) { valid = (1u << rem) - 1u; }"""]
    lines += lane_load_stmts("villains", "P.nvillains", "v0",
                             "cl_lo", "cl_hi", "    ")
    return lines


def holdem_tail():
    body = ["""
  // hero eval: revealed + drawn board + hero, uniform across lanes;
  // compressed to a 24-bit scalar for the per-group compare
  let hx_lo = P.board_lo | bd.x | P.hero_lo;
  let hx_hi = P.board_hi | bd.y | P.hero_hi;
  var x: array<word, 52>;
  var y: array<word, 24>;
  for (var p = 0u; p < 52u; p++) { x[p] = maskbit(hx_lo, hx_hi, p); }
  high_circuit(&x, &y);
  var hval = 0u;
  for (var q = 0u; q < 24u; q++) { hval = hval | ((y[q] & 1u) << q); }

  // villain lane-groups: 32 list entries per pass; holdem villain planes
  // also carry the shared board and any known villain cards
  let vx_lo = P.board_lo | bd.x | P.vill_lo;
  let vx_hi = P.board_hi | bd.y | P.vill_hi;
  var accw = 0u;
  var acct = 0u;
  var accb = 0u;"""]
    body += group_head_stmts()
    body.append("    // transpose lane masks -> plane words, low block then high block")
    body += transpose_stmts("a")
    for p in range(32):
        body.append(f"    x[{p}] = a{31 - p} | select(ZERO, ONES, ((vx_lo >> {p}u) & 1u) == 1u);")
    body += transpose_stmts("b")
    for q in range(20):
        body.append(f"    x[{32 + q}] = b{31 - q} | select(ZERO, ONES, ((vx_hi >> {q}u) & 1u) == 1u);")
    body.append("    high_circuit(&x, &y);")
    body += hval_cmp_stmts()
    body.append("""    accw = accw + countOneBits(gt & valid);
    acct = acct + countOneBits(eq & valid);
    accb = accb + countOneBits(valid);
  }
  tadd(0u, accw);
  tadd(1u, acct);
  tadd(2u, accb);
}""")
    return body


def hval_cmp_stmts():
    """Inlined MSB-first bitslice compare of villain planes y[] against the
    hero 24-bit scalar hval."""
    lines = ["""    var gt = ZERO;
    var eq = ONES;"""]
    for q in range(23, -1, -1):
        lines.append(f"""    let cq{q} = select(ZERO, ONES, ((hval >> {q}u) & 1u) == 1u);
    gt = gt | (eq & cq{q} & ~y[{q}]);
    eq = eq & ~(cq{q} ^ y[{q}]);""")
    return lines


def omaha_tail(hilo):
    body = ["""
  // full board as scalar plane masks; omaha board planes (52..103) are
  // uniform across hero and every villain group, so they are set once
  let bx_lo = P.board_lo | bd.x;
  let bx_hi = P.board_hi | bd.y;
  var x: array<word, 104>;
  var y: array<word, 24>;"""]
    if hilo:
        body.append("  var yl: array<word, 8>;")
    body.append("""  for (var p = 0u; p < 52u; p++) { x[52u + p] = maskbit(bx_lo, bx_hi, p); }

  // hero eval: hole planes broadcast, uniform across lanes; compressed to
  // scalars for the per-group compares
  for (var p = 0u; p < 52u; p++) { x[p] = maskbit(P.hero_lo, P.hero_hi, p); }
  high_circuit(&x, &y);
  var hval = 0u;
  for (var q = 0u; q < 24u; q++) { hval = hval | ((y[q] & 1u) << q); }""")
    if hilo:
        body.append("""  low_circuit(&x, &yl);
  var hlow = 0u;
  for (var q = 0u; q < 8u; q++) { hlow = hlow | ((yl[q] & 1u) << q); }""")
    body.append("""
  // villain lane-groups: 32 list entries per pass""")
    if hilo:
        body.append("  var accq = 0u;\n  var accb = 0u;\n"
                    "  // per-half breakdown accumulators (see tally layout)\n"
                    "  var accwh = 0u; var accth = 0u; var acchl = 0u;\n"
                    "  var accsl = 0u; var accnl = 0u; var accsc = 0u;")
    else:
        body.append("  var accw = 0u;\n  var acct = 0u;\n  var accb = 0u;")
    body += group_head_stmts()
    body.append("    // transpose lane masks -> plane words, low block then high block")
    body += transpose_stmts("a")
    for p in range(32):
        body.append(f"    x[{p}] = a{31 - p} | select(ZERO, ONES, ((P.vill_lo >> {p}u) & 1u) == 1u);")
    body += transpose_stmts("b")
    for q in range(20):
        body.append(f"    x[{32 + q}] = b{31 - q} | select(ZERO, ONES, ((P.vill_hi >> {q}u) & 1u) == 1u);")
    body.append("    high_circuit(&x, &y);")
    if hilo:
        body.append("    low_circuit(&x, &yl);")
    body += hval_cmp_stmts()
    if not hilo:
        body.append("""    accw = accw + countOneBits(gt & valid);
    acct = acct + countOneBits(eq & valid);
    accb = accb + countOneBits(valid);
  }
  tadd(0u, accw);
  tadd(1u, acct);
  tadd(2u, accb);
}""")
    else:
        body.append("""    let winH = gt & valid;
    let tieH = eq & valid;
    // hero's low is better when villain's low value is larger (lower = best)
    var gtL = ZERO;
    var eqL = ONES;""")
        for q in range(7, -1, -1):
            body.append(f"""    let dq{q} = select(ZERO, ONES, ((hlow >> {q}u) & 1u) == 1u);
    gtL = gtL | (eqL & yl[{q}] & ~dq{q});
    eqL = eqL & ~(dq{q} ^ yl[{q}]);""")
        body.append("""    // pot shares in quarter-pot units, matching equity_wgsl.py: each half
    // contributes 0/1/2 quarters; equal lows at the 0xff sentinel = no low,
    // and the high result claims both halves
    let heroL = gtL & valid;
    let lhAll = select(ZERO, ONES, hlow == 0xffu);
    let noLow = eqL & lhAll;
    let hasLow = ~noLow;
    let qH1 = winH;
    let qH0 = tieH;
    let qL1 = (heroL & hasLow) | (winH & noLow);
    let qL0 = ((eqL & hasLow) & valid) | (tieH & noLow);
    let s0 = qH0 ^ qL0;            // per-lane 2-bit + 2-bit add
    let c0 = qH0 & qL0;
    let s1 = qH1 ^ qL1 ^ c0;
    let s2 = (qH1 & qL1) | (c0 & (qH1 ^ qL1));
    accq = accq + countOneBits(s0) + 2u * countOneBits(s1) + 4u * countOneBits(s2);
    accb = accb + countOneBits(valid);
    accwh = accwh + countOneBits(winH);
    accth = accth + countOneBits(tieH);
    acchl = acchl + countOneBits(heroL & hasLow);
    accsl = accsl + countOneBits((eqL & hasLow) & valid);
    accnl = accnl + countOneBits(noLow & valid);
    accsc = accsc + countOneBits(winH & (noLow | (heroL & hasLow)));
  }
  tadd(0u, accq);
  tadd(1u, accb);
  tadd(2u, accwh);
  tadd(3u, accth);
  tadd(4u, acchl);
  tadd(5u, accsl);
  tadd(6u, accnl);
  tadd(7u, accsc);
}""")
    return body


def main():
    args = sys.argv[1:]
    if args == ["--selftest"]:
        selftest()
        return
    style = "holdem"
    high = low = None
    pos = []
    i = 0
    while i < len(args):
        if args[i] == "--style":
            style = args[i + 1]; i += 2
        elif args[i] == "--high":
            high = args[i + 1]; i += 2
        elif args[i] == "--low":
            low = args[i + 1]; i += 2
        else:
            pos.append(args[i]); i += 1
    (out_path,) = pos
    assert style in ("holdem", "omaha") and high
    assert low is None or style == "omaha", "--low is an omaha option"
    hilo = low is not None

    high_fn, high_inputs, high_nout = emit_circuit_fn(high, "high_circuit", "h")
    assert high_nout == 24
    nin = len(high_inputs)
    assert nin == (52 if style == "holdem" else 104)
    pc = plane_of_card(style, high_inputs)
    parts = [high_fn]

    if style == "holdem":
        meta = "style=holdem nin=52"
        body = [PROLOGUE] + holdem_tail()
    else:
        if hilo:
            low_fn, low_inputs, low_nout = emit_circuit_fn(low, "low_circuit", "l")
            assert len(low_inputs) == 104 and low_nout == 8
            parts.append(low_fn)
        meta = f"style=omaha nin=104 hilo={int(hilo)}"
        body = [PROLOGUE] + omaha_tail(hilo)

    header = emit_header(meta, pc)
    text = header + "\n\n" + "\n\n".join(parts) + "\n\n" + "\n".join(body) + "\n"
    with open(out_path, "w") as f:
        f.write(text)
    print(f"equity-bm {style}{' hi-lo' if hilo else ''}: nin={nin} -> {out_path}")


if __name__ == "__main__":
    main()
