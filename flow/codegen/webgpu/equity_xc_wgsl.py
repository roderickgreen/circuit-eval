#!/usr/bin/env python3
"""Cross-compare exact-enumeration equity kernel generator for WebGPU.

The fused kernels (equity_wgsl.py, equity_bm_wgsl.py) run the evaluation
circuit once per 32 deals.  When BOTH holes are partly unknown that is
wasteful: the deal space is the cross product hero-draws x villain-draws,
but the distinct hands on each side are only the draws themselves, so each
side's evaluations can be shared across every pairing with the other side.
This kernel evaluates each candidate hand once per board and spends the
cross product on a scalar-vs-plane compare instead of a circuit run.

One workgroup (64 threads) = one (board, hero-tile) cell:

  1. hero tile: up to 512 hero draws are evaluated bitsliced (32 lanes per
     circuit run, one lane-group per thread) and each lane's value code is
     extracted by one more 32x32 transpose -- packed hval | low << 24 --
     into workgroup memory.  Once per cell.
  2. villain tile: up to 1024 villain draws are evaluated the same way,
     but their codes stay in PLANE form (bit l of plane q = code bit q of
     lane l), stored next to the card-presence planes the input transpose
     already produced and a validity mask (villains colliding with this
     board are not deals).
  3. cross compare: each thread walks its share of the hero tile against
     every staged villain group: knock out villains sharing a card with
     the hero draw (one AND-NOT per drawn card against the staged presence
     planes), then the same MSB-first scalar-vs-plane compare and tally
     tail as the board-major kernel -- 32 deals per handful of ALU ops,
     no circuit run.

Steps 2..3 repeat until the villain list is exhausted; tallies flush to
the atomic counters once per thread.  Workgroup memory stays under the
WebGPU default 16 KiB limit, and every barrier sits in control flow whose
trip counts derive only from the uniform, never from the workgroup id, so
the WGSL uniformity analysis is satisfied everywhere.

The host (demo/src/lib/equity.ts) enumerates cells = boards x hero-tiles and
dispatches exact grids, so no workgroup is ever out of range.  Lists
arrive shuffled, so a truncated run covers a fair sample of complete
boards plus one partially covered board.

usage: equity_xc_wgsl.py --style holdem|omaha --high <high.blif>
                         [--low <low.blif>] <out.wgsl>
"""
import sys

from equity_wgsl import (emit_circuit_fn, plane_of_card, transpose_stmts,
                         lane_load_stmts, selftest)

HT = 512   # heroes per cell (per workgroup)
VG = 32    # villain lane-groups per tile (32 x 32 = 1024 villains)


def emit_header(meta, pc, hilo):
    yl_decl = f"\nvar<workgroup> sh_yl: array<u32, {VG * 8}>;   // low-code planes" if hilo else ""
    return f"""// generated by equity_xc_wgsl.py -- do not edit
// meta: equity-xc {meta} ht={HT} vg={VG}
// planeOfCard: {",".join(map(str, pc))}
alias word = u32;
const ZERO = 0u;
const ONES = 0xffffffffu;

struct Params {{
  hero_lo: u32,    // KNOWN hero holes, plane space (draws live in the list)
  hero_hi: u32,
  vill_lo: u32,    // known villain holes
  vill_hi: u32,
  board_lo: u32,   // revealed board mask, plane space
  board_hi: u32,
  nboards: u32,    // board list length
  nvillains: u32,  // villain list length
  nheroes: u32,    // hero list length
  cellbase: u32,   // first cell of this dispatch; a cell is one
                   // (board, hero-tile) pair and one workgroup
  ntspan: u32,     // hero tiles per board in this chunk's slice
  bbase: u32,      // first board of this chunk's board range
  htbase: u32,     // first hero tile of this chunk's hero slice
}}
@group(0) @binding(0) var<uniform> P: Params;
// work lists, built host-side (demo/src/lib/worklist.ts): one entry per
// combination of drawn cards, as a plane-space mask pair (.x holds planes
// 0..31, .y planes 32..51)
@group(0) @binding(1) var<storage, read> boards: array<vec2<u32>>;
@group(0) @binding(2) var<storage, read> villains: array<vec2<u32>>;
@group(0) @binding(3) var<storage, read> heroes: array<vec2<u32>>;
// counter i is the u64 pair (tally[2i], tally[2i+1]) -- big spots overflow
// a single u32 (matches the other equity kernels)
@group(0) @binding(4) var<storage, read_write> tally: array<atomic<u32>>;

fn tadd(i: u32, x: u32) {{
  let old = atomicAdd(&tally[2u * i], x);
  if (old > ONES - x) {{ atomicAdd(&tally[2u * i + 1u], 1u); }}
}}

fn maskbit(lo: u32, hi: u32, p: u32) -> word {{
  var w = lo;
  if (p >= 32u) {{ w = hi; }}
  if (((w >> (p & 31u)) & 1u) == 1u) {{ return ONES; }}
  return ZERO;
}}

// staged villain tile, shared across the workgroup.  Group g of the tile
// occupies sh_y[g*24..], sh_card[g*52..], sh_valid[g]:
//   sh_y     value-code planes straight from the circuit (bit l of plane
//            q = code bit q of villain lane l)
//   sh_card  card-presence planes from the input transpose (bit l of
//            plane p = villain lane l holds the card on plane p), for the
//            per-hero collision knockout
//   sh_valid lanes that are real list entries and don't collide with the
//            board
var<workgroup> sh_y: array<u32, {VG * 24}>;
var<workgroup> sh_card: array<u32, {VG * 52}>;
var<workgroup> sh_valid: array<u32, {VG}>;{yl_decl}
// hero tile: packed per-hero value codes (hval | low << 24) and per-group
// validity masks
var<workgroup> sh_hcode: array<u32, {HT}>;
var<workgroup> sh_hvalid: array<u32, {HT // 32}>;"""


def code_pack_stmts(hilo, ind):
    """Stack the circuit output planes as transpose rows and extract one
    packed scalar code per lane: bits 0..23 = hval, 24..31 = low (or zero).
    Rows load reversed (row r -> c{31-r}) and lanes read reversed
    (lane l -> c{31-l}), matching transpose_stmts."""
    lines = []
    decls = []
    for q in range(24):
        decls.append(f"var c{31 - q} = y[{q}];")
    if hilo:
        for q in range(8):
            decls.append(f"var c{7 - q} = yl[{q}];")
    else:
        decls.append(" ".join(f"var c{7 - q} = ZERO;" for q in range(8)))
    for i in range(0, len(decls), 4):
        lines.append(ind + " ".join(decls[i:i + 4]))
    lines += transpose_stmts("c", ind)
    for l in range(32):
        lines.append(f"{ind}sh_hcode[t * 32u + {l}u] = c{31 - l};")
    return lines


def hero_phase(style, hilo):
    """Evaluate this cell's hero tile into sh_hcode/sh_hvalid: one
    lane-group of 32 hero draws per thread, bitsliced through the circuit,
    then one more transpose to per-lane scalars."""
    ind = "    "
    lines = ["""  // hero tile eval: threads 0..hgroups-1 each run one lane-group of 32
  // hero draws through the circuit and extract per-lane packed codes
  if (t < hgroups) {
    let h0 = hbase + t * 32u;
    var valid = ONES;
    let hrem = P.nheroes - h0;
    if (hrem < 32u) { valid = (1u << hrem) - 1u; }"""]
    lines += lane_load_stmts("heroes", "P.nheroes", "h0", "bd.x", "bd.y", ind)
    lines.append(ind + "// transpose lane masks -> plane words, low then high block")
    lines += transpose_stmts("a", ind)
    lines += transpose_stmts("b", ind)
    if style == "holdem":
        lines.append(f"""{ind}var x: array<word, 52>;
{ind}var y: array<word, 24>;
{ind}let hu_lo = P.board_lo | bd.x | P.hero_lo;
{ind}let hu_hi = P.board_hi | bd.y | P.hero_hi;""")
        for p in range(32):
            lines.append(f"{ind}x[{p}] = a{31 - p} | select(ZERO, ONES, ((hu_lo >> {p}u) & 1u) == 1u);")
        for q in range(20):
            lines.append(f"{ind}x[{32 + q}] = b{31 - q} | select(ZERO, ONES, ((hu_hi >> {q}u) & 1u) == 1u);")
        lines.append(ind + "high_circuit(&x, &y);")
    else:
        lines.append(f"""{ind}var x: array<word, 104>;
{ind}var y: array<word, 24>;""")
        if hilo:
            lines.append(ind + "var yl: array<word, 8>;")
        lines.append(f"""{ind}let bx_lo = P.board_lo | bd.x;
{ind}let bx_hi = P.board_hi | bd.y;
{ind}for (var p = 0u; p < 52u; p++) {{ x[52u + p] = maskbit(bx_lo, bx_hi, p); }}""")
        for p in range(32):
            lines.append(f"{ind}x[{p}] = a{31 - p} | select(ZERO, ONES, ((P.hero_lo >> {p}u) & 1u) == 1u);")
        for q in range(20):
            lines.append(f"{ind}x[{32 + q}] = b{31 - q} | select(ZERO, ONES, ((P.hero_hi >> {q}u) & 1u) == 1u);")
        lines.append(ind + "high_circuit(&x, &y);")
        if hilo:
            lines.append(ind + "low_circuit(&x, &yl);")
    lines += code_pack_stmts(hilo, ind)
    lines.append(f"{ind}sh_hvalid[t] = valid;")
    lines.append("  }")
    return lines


def stage_phase(style, hilo):
    """Evaluate one villain tile into the staged planes: threads
    0..ngrps-1 each run one lane-group of 32 villain draws."""
    ind = "      "
    lines = ["""    if (t < ngrps) {
      let v0 = (g0 + t) * 32u;
      var valid = ONES;
      let vrem = P.nvillains - v0;
      if (vrem < 32u) { valid = (1u << vrem) - 1u; }"""]
    lines += lane_load_stmts("villains", "P.nvillains", "v0", "bd.x", "bd.y", ind)
    lines.append(ind + "// transpose lane masks -> plane words, low then high block")
    lines += transpose_stmts("a", ind)
    lines += transpose_stmts("b", ind)
    lines.append(ind + "// card-presence planes feed the per-hero collision knockout")
    for p in range(32):
        lines.append(f"{ind}sh_card[t * 52u + {p}u] = a{31 - p};")
    for q in range(20):
        lines.append(f"{ind}sh_card[t * 52u + {32 + q}u] = b{31 - q};")
    if style == "holdem":
        lines.append(f"""{ind}var x: array<word, 52>;
{ind}var y: array<word, 24>;
{ind}let vu_lo = P.board_lo | bd.x | P.vill_lo;
{ind}let vu_hi = P.board_hi | bd.y | P.vill_hi;""")
        for p in range(32):
            lines.append(f"{ind}x[{p}] = a{31 - p} | select(ZERO, ONES, ((vu_lo >> {p}u) & 1u) == 1u);")
        for q in range(20):
            lines.append(f"{ind}x[{32 + q}] = b{31 - q} | select(ZERO, ONES, ((vu_hi >> {q}u) & 1u) == 1u);")
        lines.append(ind + "high_circuit(&x, &y);")
    else:
        lines.append(f"""{ind}var x: array<word, 104>;
{ind}var y: array<word, 24>;""")
        if hilo:
            lines.append(ind + "var yl: array<word, 8>;")
        lines.append(f"""{ind}let bx_lo = P.board_lo | bd.x;
{ind}let bx_hi = P.board_hi | bd.y;
{ind}for (var p = 0u; p < 52u; p++) {{ x[52u + p] = maskbit(bx_lo, bx_hi, p); }}""")
        for p in range(32):
            lines.append(f"{ind}x[{p}] = a{31 - p} | select(ZERO, ONES, ((P.vill_lo >> {p}u) & 1u) == 1u);")
        for q in range(20):
            lines.append(f"{ind}x[{32 + q}] = b{31 - q} | select(ZERO, ONES, ((P.vill_hi >> {q}u) & 1u) == 1u);")
        lines.append(ind + "high_circuit(&x, &y);")
        if hilo:
            lines.append(ind + "low_circuit(&x, &yl);")
    for q in range(24):
        lines.append(f"{ind}sh_y[t * 24u + {q}u] = y[{q}];")
    if hilo:
        for q in range(8):
            lines.append(f"{ind}sh_yl[t * 8u + {q}u] = yl[{q}];")
    lines.append(f"{ind}sh_valid[t] = valid;")
    lines.append("    }")
    return lines


def compare_phase(hilo):
    """The cross product: each thread strides its heroes over every staged
    villain group -- collision knockout, MSB-first scalar-vs-plane
    compare(s), and the same tally algebra as the board-major kernels."""
    ind = "        "
    lines = ["""    // cross compare: thread t owns heroes t, t+64, ... of this tile
    for (var hi = t; hi < nhero; hi += 64u) {
      if ((sh_hvalid[hi >> 5u] & (1u << (hi & 31u))) == 0u) { continue; }
      let code = sh_hcode[hi];
      let hval = code & 0xffffffu;"""]
    if hilo:
        lines.append("      let hlow = code >> 24u;")
    lines.append("""      let hd = heroes[hbase + hi];
      for (var grp = 0u; grp < ngrps; grp++) {
        var valid = sh_valid[grp];
        // villains sharing a card with this hero's draw are not deals
        for (var m = hd.x; m != 0u; m = m & (m - 1u)) {
          valid = valid & ~sh_card[grp * 52u + firstTrailingBit(m)];
        }
        for (var m = hd.y; m != 0u; m = m & (m - 1u)) {
          valid = valid & ~sh_card[grp * 52u + 32u + firstTrailingBit(m)];
        }
        if (valid == 0u) { continue; }
        var gt = ZERO;
        var eq = ONES;""")
    for q in range(23, -1, -1):
        lines.append(f"""{ind}let yq{q} = sh_y[grp * 24u + {q}u];
{ind}let cq{q} = select(ZERO, ONES, ((hval >> {q}u) & 1u) == 1u);
{ind}gt = gt | (eq & cq{q} & ~yq{q});
{ind}eq = eq & ~(cq{q} ^ yq{q});""")
    if not hilo:
        lines.append("""        accw = accw + countOneBits(gt & valid);
        acct = acct + countOneBits(eq & valid);
        accb = accb + countOneBits(valid);
      }
    }""")
    else:
        lines.append("""        let winH = gt & valid;
        let tieH = eq & valid;
        // hero's low is better when villain's low value is larger
        var gtL = ZERO;
        var eqL = ONES;""")
        for q in range(7, -1, -1):
            lines.append(f"""{ind}let ylq{q} = sh_yl[grp * 8u + {q}u];
{ind}let dq{q} = select(ZERO, ONES, ((hlow >> {q}u) & 1u) == 1u);
{ind}gtL = gtL | (eqL & ylq{q} & ~dq{q});
{ind}eqL = eqL & ~(dq{q} ^ ylq{q});""")
        lines.append("""        // pot shares in quarter-pot units, matching the fused kernels:
        // each half contributes 0/1/2 quarters; equal lows at the 0xff
        // sentinel = no low, and the high result claims both halves
        let heroL = gtL & valid;
        let lhAll = select(ZERO, ONES, hlow == 0xffu);
        let noLow = eqL & lhAll;
        let hasLow = ~noLow;
        let qH1 = winH;
        let qH0 = tieH;
        let qL1 = (heroL & hasLow) | (winH & noLow);
        let qL0 = ((eqL & hasLow) & valid) | (tieH & noLow);
        let s0 = qH0 ^ qL0;            // per-lane 2-bit + 2-bit add
        let c0 = qH0 & qL0;
        let s1 = qH1 ^ qL1 ^ c0;
        let s2 = (qH1 & qL1) | (c0 & (qH1 ^ qL1));
        accq = accq + countOneBits(s0) + 2u * countOneBits(s1) + 4u * countOneBits(s2);
        accb = accb + countOneBits(valid);
        accwh = accwh + countOneBits(winH);
        accth = accth + countOneBits(tieH);
        acchl = acchl + countOneBits(heroL & hasLow);
        accsl = accsl + countOneBits((eqL & hasLow) & valid);
        accnl = accnl + countOneBits(noLow & valid);
        accsc = accsc + countOneBits(winH & (noLow | (heroL & hasLow)));
      }
    }""")
    return lines


def emit_body(style, hilo):
    lines = [f"""@compute @workgroup_size(64)
fn main_equity_xc(@builtin(workgroup_id) wg: vec3<u32>,
    @builtin(local_invocation_index) t: u32) {{
  // cell = one (board, hero-tile) pair.  The host dispatches exact grids,
  // so every workgroup maps to a live cell and there is no early return
  // (the barriers below require uniform control flow).
  let cell = P.cellbase + wg.x;
  let bIdx = P.bbase + cell / P.ntspan;
  let ht = P.htbase + cell % P.ntspan;
  let bd = boards[bIdx];
  let hbase = ht * {HT}u;
  let nhero = min({HT}u, P.nheroes - hbase);
  let hgroups = (nhero + 31u) / 32u;"""]
    if hilo:
        lines.append("""  var accq = 0u;
  var accb = 0u;
  // per-half breakdown accumulators (see tally layout)
  var accwh = 0u; var accth = 0u; var acchl = 0u;
  var accsl = 0u; var accnl = 0u; var accsc = 0u;""")
    else:
        lines.append("  var accw = 0u;\n  var acct = 0u;\n  var accb = 0u;")
    lines += hero_phase(style, hilo)
    lines.append(f"""
  // villain tiles: {VG} lane-groups ({VG * 32} draws) staged per pass.
  // Trip counts depend only on the uniform, keeping every barrier in
  // workgroup-uniform control flow.
  let vgAll = (P.nvillains + 31u) / 32u;
  let vtiles = (vgAll + {VG - 1}u) / {VG}u;
  for (var vt = 0u; vt < vtiles; vt++) {{
    workgroupBarrier();
    let g0 = vt * {VG}u;
    let ngrps = min({VG}u, vgAll - g0);""")
    lines += stage_phase(style, hilo)
    lines.append("    workgroupBarrier();")
    lines += compare_phase(hilo)
    lines.append("  }")
    if hilo:
        lines.append("""  tadd(0u, accq);
  tadd(1u, accb);
  tadd(2u, accwh);
  tadd(3u, accth);
  tadd(4u, acchl);
  tadd(5u, accsl);
  tadd(6u, accnl);
  tadd(7u, accsc);
}""")
    else:
        lines.append("""  tadd(0u, accw);
  tadd(1u, acct);
  tadd(2u, accb);
}""")
    return lines


def main():
    args = sys.argv[1:]
    if args == ["--selftest"]:
        selftest()
        return
    style = "holdem"
    high = low = None
    pos = []
    i = 0
    while i < len(args):
        if args[i] == "--style":
            style = args[i + 1]; i += 2
        elif args[i] == "--high":
            high = args[i + 1]; i += 2
        elif args[i] == "--low":
            low = args[i + 1]; i += 2
        else:
            pos.append(args[i]); i += 1
    (out_path,) = pos
    assert style in ("holdem", "omaha") and high
    assert low is None or style == "omaha", "--low is an omaha option"
    hilo = low is not None

    high_fn, high_inputs, high_nout = emit_circuit_fn(high, "high_circuit", "h")
    assert high_nout == 24
    nin = len(high_inputs)
    assert nin == (52 if style == "holdem" else 104)
    pc = plane_of_card(style, high_inputs)
    parts = [high_fn]
    if hilo:
        low_fn, low_inputs, low_nout = emit_circuit_fn(low, "low_circuit", "l")
        assert len(low_inputs) == 104 and low_nout == 8
        parts.append(low_fn)

    meta = f"style={style} nin={nin} hilo={int(hilo)}"
    header = emit_header(meta, pc, hilo)
    body = emit_body(style, hilo)
    text = header + "\n\n" + "\n\n".join(parts) + "\n\n" + "\n".join(body) + "\n"
    with open(out_path, "w") as f:
        f.write(text)
    print(f"equity-xc {style}{' hi-lo' if hilo else ''}: nin={nin} -> {out_path}")


if __name__ == "__main__":
    main()
