#!/usr/bin/env python3
"""BLIF -> bitsliced C over plain uint64_t. The teaching backend.

Where bitslice.py chases speed (vector words of BS_BATCH lanes), this
backend chases readability: every BLIF gate becomes exactly one C
statement over a uint64_t, in topological order. The production backend
emits the same one-statement-per-gate code at the target's vector width
-- that width is the main difference. The BLIF front end (parse, topo,
gate_expr) is shared across backends in ../blif.py.

The bitslice idea in one sentence: run 64 independent evaluations of the
circuit at once by giving every wire a 64-bit word whose bit i belongs to
evaluation i -- then each logic gate is a single C bitwise operator.

usage: bitslice64.py <in.blif> <out.c> [--name FUNC]
  --name FUNC   name of the emitted C function (default: the BLIF .model)
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from blif import parse, topo, gate_expr

# ---- command line ----
args = sys.argv[1:]
func = None
pos = []
i = 0
while i < len(args):
    if args[i] == "--name":
        func = args[i + 1]; i += 2
    else:
        pos.append(args[i]); i += 1
blif_path, out_path = pos

model, inputs, outputs, gates = parse(blif_path)
if func is None:
    func = "".join(c if c.isalnum() else "_" for c in model)

order = topo(inputs, outputs, gates)

# ---- name every wire as a C identifier ----
# inputs and outputs keep their BLIF names, so the generated C reads with
# the same port names as the Verilog it came from; internal wires become
# t0, t1, ... in emit order so the code reads top to bottom.
used = set()


def uniq(n):
    """n, made distinct from every name handed out so far."""
    while n in used:
        n += "_"
    used.add(n)
    return n


def cident(w, default):
    """The BLIF wire name as a C identifier, or default when the BLIF has
    no usable one (a name ABC mangled, or one starting with a digit)."""
    n = "".join(c if c.isalnum() else "_" for c in w)
    return uniq(default if not n or n[0].isdigit() else n)


cname = {}
for k, w in enumerate(inputs):
    cname[w] = cident(w, f"x{k}")
for k, w in enumerate(outputs):
    if w not in cname:  # an output can be driven straight by an input
        cname[w] = cident(w, f"y{k}")
for k, w in enumerate([w for w in order if w not in cname]):
    cname[w] = uniq(f"t{k}")

# ---- emit ----
with open(out_path, "w") as f:
    W = f.write
    W(f"/* generated by bitslice64.py from {blif_path} -- do not edit */\n")
    W("#include <stdint.h>\n\n")
    W("/* 64 evaluations per call: bit i of every word belongs to\n")
    W(f"   evaluation i. in[{len(inputs)}] and out[{len(outputs)}] follow"
      " the BLIF port order. */\n")
    W(f"void {func}(const uint64_t *in, uint64_t *out) {{\n")
    for k, w in enumerate(inputs):
        W(f"    uint64_t {cname[w]} = in[{k}];\n")
    W("\n")
    for n in order:
        e = gate_expr(*gates[n], ref=cname.__getitem__, ones="~0ull", zero="0")
        W(f"    uint64_t {cname[n]} = {e};\n")
    W("\n")
    for k, w in enumerate(outputs):
        tag = "" if cname[w] == w else f"  /* {w} */"
        W(f"    out[{k}] = {cname[w]};{tag}\n")
    W("}\n")

print(f"{out_path}: {len(inputs)} inputs, {len(outputs)} outputs, "
      f"{len(order)} gates")
